// Recover a group's last known site when WhatsApp temporarily fails to return
// the chat title. Prefer a real site over a transient "Unknown Site" row left
// by an earlier lookup failure.
export async function savedSiteNameForGroup(groupId) {
  await sql.unsafe(SITES_REGISTRY);
  const rows = await sql`
    select site_name
    from public.sites
    where group_id = ${groupId}
    order by (lower(site_name) = 'unknown site') asc, last_seen_at desc
    limit 1
  `;
  return rows[0]?.site_name || null;
}

/**
 * Move the single shared set of tables (public.progress, public.issues, ...) into
 * a site schema. Run once for the site that owned the old shared data.
 * public.* is left untouched, so this is safe to run and safe to undo.
 */
export async function migratePublicTablesToSite({ siteName, groupId, tables = ['progress', 'materials', 'issues', 'work_orders', 'attendance', 'diary', 'milestones'] } = {}) {
  const { schema } = await ensureSiteSchema({ siteName, groupId });
  const copied = [];
  for (const t of tables) {
    if (!/^[a-z_]+$/.test(t)) throw new Error(`bad table name: ${t}`);
    const res = await sql.begin(async (tx) => {
      await tx`SET LOCAL search_path TO ${sql(schema)}, public`;
      const rows = await tx`select * from public.${sql(t)}`;
      if (!rows.length) return { table: t, copied: 0 };
      const cols = Object.keys(rows[0]);
      const colList = cols.map((c) => `"${c}"`).join(', ');
      const placeholders = cols.map((_, i) => `$${i + 1}`).join(', ');
      for (const row of rows) {
        await tx.unsafe(
          `insert into "${schema}"."${t}" (${colList}) values (${placeholders})
           on conflict do nothing`,
          cols.map((c) => row[c])
        );
      }
      return { table: t, copied: rows.length };
    });
    copied.push(res);
  }

  // The copied rows carry their ids, so the identity sequences must catch up -
  // otherwise the next insert asks for id 1 and hits issues_pkey.
  await syncIdentitySequences(schema);

  return { schema, copied };
}

// Run a query with $1, $2... placeholders. undefined/NaN -> NULL so a bad
// id (e.g. parseInt('abc')) just matches nothing, as it did under SQLite.
// When a site scope is active the whole statement runs inside a transaction with
// that site's schema first on search_path - that is what isolates the sites.
const q = async (text, ...params) => {
  const site = siteScope.getStore();
  const values = params.map((p) => (p === undefined || Number.isNaN(p) ? null : p));
  if (!site || !site.schema) return sql.unsafe(text, values);
  return sql.begin(async (t) => {
    await t`SET LOCAL search_path TO ${sql(site.schema)}, public`;
    return t.unsafe(text, values);
  });
};
const one = async (text, ...params) => (await q(text, ...params))[0];
const insert = async (text, ...params) => ({ lastInsertRowid: (await one(text + ' RETURNING id', ...params)).id });
const change = async (text, ...params) => ({ changes: (await q(text, ...params)).count });

