// SSL for Supabase; a local test DB (localhost) doesn't speak it.
const isLocal = /@(localhost|127\.0\.0\.1)[:/]/.test(config.databaseUrl);
// Postgres NOTICEs are informational, not errors. `CREATE SCHEMA IF NOT EXISTS` /
// `CREATE TABLE IF NOT EXISTS` emit one per object on EVERY run, so a first-use
// `.progress` in a group buried the terminal under ~15 notice dumps and buried any
// real warning in the same flood. Routine idempotent-DDL notices are dropped; any
// other notice still surfaces as a warning.
const ROUTINE_DDL = /already exists, skipping/i;
export const sql = postgres(config.databaseUrl, {
  ssl: isLocal ? false : 'require',
  onnotice: (notice) => {
    const message = notice?.message || '';
    if (ROUTINE_DDL.test(message)) return;
    const severity = notice?.severity_local || notice?.severity || 'NOTICE';
    console.warn(`âš ï¸  Postgres ${severity}: ${message}${notice?.code ? ` (${notice.code})` : ''}`);
  },
});

// --- ONE DATABASE PER SITE ---------------------------------------------------
// Every site group gets its own Postgres SCHEMA ("folder") holding its own
// progress / materials / issues / attendance / diary / work_orders / milestones.
// Without this, every group shared one set of tables, so opening issues in a new
// site group showed the OLD site's issues.
//
// The schema is selected with `SET LOCAL search_path` inside a transaction, which
// means the ~60 SQL strings below did not have to change at all - they still say
// "FROM issues", and Postgres resolves that to the current site's schema.
//
// AsyncLocalStorage (not a module-level variable) so two groups being handled at
// the same moment cannot swap each other's database.
const siteScope = new AsyncLocalStorage();

export function currentSite() {
  return siteScope.getStore() || null;
}

/** Run fn() with every DB call bound to `site`. */
export function runInSite(site, fn) {
  return siteScope.run(site || null, fn);
}

// A schema name goes into SQL as an identifier (it cannot be a parameter), so it
// is generated by us and then validated again here.
const SCHEMA_NAME = /^[a-z_][a-z0-9_]{0,50}$/;
function assertSchema(name) {
  if (!SCHEMA_NAME.test(String(name || ''))) {
    throw new Error(`refusing to use an unsafe schema name: ${name}`);
  }
  return name;
}

/**
 * Stable schema name for a site group. The slug makes it readable in the
 * Supabase table list; the hash of the group id keeps two sites that happen to
 * share a name (or a rename) from colliding.
 */
export function schemaNameFor(siteName, groupId) {
  const slug = String(siteName || 'site')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 24) || 'site';
  const hash = crypto.createHash('sha1').update(String(groupId || siteName)).digest('hex').slice(0, 6);
  return assertSchema(`site_${slug}_${hash}`);
}

