  async list(jid, month) {
    await ensurePersonalSchema();
    return q(
      `SELECT * FROM "${PERSONAL_SCHEMA}".personal_claims
       WHERE jid = $1 AND month = $2 ORDER BY id ASC`,
      jid, month
    );
  },

  async monthTotals() {
    await ensurePersonalSchema();
    return q(
      `SELECT jid, month,
              count(*)::int AS receipt_count,
              count(*) FILTER (WHERE amount > 0)::int AS counted_count,
              coalesce(sum(amount), 0)::float8 AS total
       FROM "${PERSONAL_SCHEMA}".personal_claims
       WHERE compiled_at IS NULL
       GROUP BY jid, month ORDER BY month DESC, jid`
    );
  },

