/**
 * Everything said in the group.
 *
 * Before this, "context" was an in-memory array of the last few messages that
 * died on restart, so the bot forgot anything older than the current screen. Now
 * every message is a row, which makes three things possible: recall by keyword,
 * recall across restarts, and the bot knowing what was ALREADY said so it does
 * not ask the same question twice.
 */
export const chatLogDB = {
  add(data) {
    return insert(`
      INSERT INTO chat_log (date, sender, sender_id, is_bot, body, kind)
      VALUES ($1, $2, $3, $4, $5, $6)
    `, data.date, data.sender || null, data.senderId || null,
       data.isBot === true, data.body || null, data.kind || null);
  },

  /** Last N messages, oldest first - the sliding window the model sees. */
  getRecent(limit = 30) {
    return q(`SELECT * FROM (
                SELECT * FROM chat_log ORDER BY id DESC LIMIT $1
              ) t ORDER BY id ASC`, limit);
  },

  /**
   * Search what people actually said. Multi-word terms are AND-ed so
   * "paip bumbung" does not match every message containing "paip".
   */
  search(term, limit = 12) {
    const words = String(term || '')
      .split(/\s+/)
      .map((w) => w.replace(/[^\p{L}\p{N}]/gu, ''))
      .filter((w) => w.length > 1)
      .slice(0, 5);
    if (!words.length) return Promise.resolve([]);
    const clause = words.map((_, i) => `body ILIKE '%' || $${i + 1} || '%'`).join(' AND ');
    const ids = words;
    const rest = [];
    ids.forEach((v, i) => rest.push(v));
    rest.push(limit);
    return q(`SELECT * FROM chat_log
              WHERE ${clause}
              ORDER BY id DESC LIMIT $${words.length + 1}`, ...rest);
  },

  /** How many messages one person has sent - used to know who keeps asking. */
  countBySender(senderId) {
    return q('SELECT count(*)::int as n FROM chat_log WHERE sender_id = $1', senderId);
  },

  delete(id) {
    return change('DELETE FROM chat_log WHERE id = $1', id);
  },

  /**
   * Trim old history. Chat grows without bound and it is all re-read into the
   * prompt; keep a recent window plus anything still relevant.
   */
  prune(keepDays = 30) {
    // `date` is stored as DD/MM/YYYY text, not a date column, so both sides
    // need casting: a bare text - interval is rejected ("operator does not
    // exist: text - interval"). Comparing as ::date keeps the DD/MM/YYYY
    // ordering correct, which to_char would not have.
    return change(
      `DELETE FROM chat_log
        WHERE date ~ '^\\d{2}/\\d{2}/\\d{4}$'
          AND date::date < (local_now() - make_interval(days => $1::int))::date`,
      keepDays
    );
  },
};

/**
 * Search several columns at once, chosen by the caller from a fixed whitelist.
 *
 * Built here rather than per-table because "cari progress paip" has to look in
 * description AND location AND reporter, and every table only knowing about its
 * own `search()` meant a near-duplicate method per table.
 *
 * A `function` declaration, not an arrow const, on purpose: the DB objects above
 * call it at module-eval time, and a const threw "Cannot access before
 * initialization" on the very first import.
 */
function searchFieldsFor(table, columns) {
  return (fields, term, limit = 20) => {
    const clean = String(term || '').trim();
    if (!clean || !Array.isArray(fields) || !fields.length) return Promise.resolve([]);
    // Only allow columns this table actually has, so a caller cannot inject SQL.
    const safe = fields.filter((f) => columns.includes(f));
    if (!safe.length) return Promise.resolve([]);
    const clause = safe.map((c, i) => `${c} ILIKE '%' || $${i + 1} || '%'`).join(' OR ');
    const params = [...safe.map(() => clean), limit];
    return q(`SELECT * FROM ${table} WHERE ${clause} ORDER BY id DESC LIMIT $${safe.length + 1}`, ...params);
  };
}

/**
 * Promised work that is not closed yet.
 *
 * The company notes ask for a pending list ("track until done"), and this is it.
 * Open items can be asked about, filtered by status, and closed when evidence
 * arrives - so follow-up is data-driven rather than something the model has to
 * remember to volunteer.
 */
export const pendingDB = {
  add(data) {
    return insert(`
      INSERT INTO pending_items (date, task, pic, location, due_date, status, priority, notes, raised_by)
      VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
    `, data.date, data.task, data.pic || null, data.location || null,
       data.dueDate || null, data.status || 'open', data.priority || null,
       data.notes || null, data.raisedBy || null);
  },

  getById(id) {
    return one('SELECT * FROM pending_items WHERE id = $1', id);
  },

  searchFields: searchFieldsFor('pending_items', ['task', 'pic', 'location', 'notes', 'raised_by']),

  getRecent(limit = 20) {
    return q('SELECT * FROM pending_items ORDER BY id DESC LIMIT $1', limit);
  },

  /** The live list. `open` means not finished, whatever the exact status word. */
  getOpen(limit = 30) {
    return q(`SELECT * FROM pending_items
              WHERE status IN ('open', 'in_progress', 'blocked', 'waiting')
              ORDER BY
                CASE priority WHEN 'urgent' THEN 0 WHEN 'high' THEN 1
                              WHEN 'medium' THEN 2 ELSE 3 END,
                created_at DESC
              LIMIT $1`, limit);
  },

  search(term, limit = 12) {
    const words = String(term || '')
      .split(/\s+/)
      .map((w) => w.replace(/[^\p{L}\p{N}]/gu, ''))
      .filter((w) => w.length > 1)
      .slice(0, 5);
    if (!words.length) return Promise.resolve([]);
    const clause = words.map((_, i) => `(task ILIKE '%' || $${i + 1} || '%' OR notes ILIKE '%' || $${i + 1} || '%')`).join(' AND ');
    const rest = words.slice();
    rest.push(limit);
    return q(`SELECT * FROM pending_items WHERE ${clause} ORDER BY id DESC LIMIT $${words.length + 1}`, ...rest);
  },

  update(id, data) {
    return applyUpdate('pending_items', {
      task: 'task',
      pic: 'pic',
      location: 'location',
      dueDate: 'due_date',
      status: 'status',
      priority: 'priority',
      notes: 'notes',
      closedAt: 'closed_at',
    }, id, data);
  },

  /** Close one, stamping closed_at so history stays meaningful. */
  close(id, notes = null) {
    // Append to the notes rather than replace them. The stored notes are the
    // reason the item was raised ("tapis dari paip respons dalam 2 jam") and are
    // the only record of it once closed - overwriting them with the closing note
    // destroyed the original instruction.
    return change(
      `UPDATE pending_items
          SET status = 'done',
              closed_at = local_now(),
              notes = CASE
                WHEN $2::text IS NULL THEN notes
                WHEN notes IS NULL OR notes = '' THEN $2::text
                ELSE notes || E'\\n[closed] ' || $2::text
              END
        WHERE id = $1`,
      id, notes
    );
  },

  delete(id) {
    return change('DELETE FROM pending_items WHERE id = $1', id);
  },
};
