/**
 * Point each table's identity sequence at max(id) + 1.
 *
 * Copying rows into a site schema brings their id values with them, but the new
 * sequence still starts at 1 - so the next insert tries id 1 again and Postgres
 * answers: duplicate key value violates unique constraint "issues_pkey".
 * Done here so it cannot bite on any site, migrated or not.
 */
export async function syncIdentitySequences(schema) {
  for (const table of TABLE_NAMES) {
    await sql.unsafe(`
      select setval(
        pg_get_serial_sequence('"${schema}"."${table}"', 'id'),
        coalesce((select max(id) from "${schema}"."${table}"), 0) + 1,
        false
      )
    `);
  }
}

const readySchemas = new Set();

/**
 * Bump when SITE_TABLES gains a table or column. Existing site schemas were
 * created by an older build and never re-run the DDL, so a new table simply did
 * not exist there ("relation chat_log does not exist") even though every
 * `CREATE TABLE IF NOT EXISTS` looked harmless. Recording the version in the
 * schema means an old one gets upgraded on its next message instead of failing
 * forever.
 */
const SCHEMA_VERSION = 6;

async function currentSchemaVersion(schema) {
  const rows = await sql.unsafe(
    `select value from "${schema}".schema_meta where key = 'version' limit 1`
  ).catch(() => []);
  return rows.length ? parseInt(rows[0].value, 10) || 0 : 0;
}

/**
 * Make sure this site has its own empty database, and return the site handle to
 * hand to runInSite(). Called once per new group - after that it is a cache hit.
 */
export async function ensureSiteSchema({ siteName, groupId } = {}) {
  const schema = schemaNameFor(siteName, groupId);
  const site = { schema, siteName: siteName || schema, groupId: groupId || null };
  if (readySchemas.has(schema)) return site;

  await sql.unsafe(SITES_REGISTRY);
  const version = await currentSchemaVersion(schema);
  if (version >= SCHEMA_VERSION) {
    readySchemas.add(schema);
    return site;
  }

  await sql.begin(async (t) => {
    await t`CREATE SCHEMA IF NOT EXISTS ${sql(schema)}`;
    await t`SET LOCAL search_path TO ${sql(schema)}, public`;
    // Stamped BEFORE the DDL so the version query never sees a half-created
    // schema_meta and decides the site is already up to date.
    await t.unsafe(
      `create table if not exists schema_meta (key text primary key, value text not null, updated_at text default local_now())`
    );
    for (const ddl of SITE_TABLES) await t.unsafe(ddl);
    // Same posture as the shared tables in supabase/schema.sql: locked away from
    // the public anon API. The bot connects with the DB password, so it is the
    // owner and RLS does not block it.
    for (const table of SITE_TABLES.map((d) => /create table if not exists (\w+)/.exec(d)?.[1]).filter(Boolean)) {
      await t.unsafe(`alter table "${schema}"."${table}" enable row level security`);
    }
  });

  // Self-heal: if rows ever arrived with explicit ids (a migration, a copy), the
  // sequence has to be moved past them or the next insert collides.
  await syncIdentitySequences(schema);

  await sql.unsafe(
    `insert into "${schema}".schema_meta (key, value) values ('version', '${SCHEMA_VERSION}')
     on conflict (key) do update set value = excluded.value, updated_at = local_now()`
  );

  await sql`
    insert into public.sites (site_name, schema_name, group_id, last_seen_at)
    values (${site.siteName}, ${schema}, ${site.groupId}, local_now())
    on conflict (schema_name) do update
      set site_name = excluded.site_name,
          group_id = excluded.group_id,
          last_seen_at = excluded.last_seen_at
  `;

  readySchemas.add(schema);
  // Prefixed and demoted on purpose. This used to print as a bare line right
  // before the first command's reply, so it looked like the bot failing to
  // attach / failing at something. It is internal plumbing, not chat.
  console.log(`[db] schema ready (pre-created): "${site.siteName}" -> "${schema}"`);
  return site;
}

