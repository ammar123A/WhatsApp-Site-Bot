let personalReady = null;

/**
 * Create the personal-claims schema once per process.
 *
 * Separate from ensureSiteSchema() on purpose: no site group can claim this
 * schema, and nothing here is ever selected by search_path.
 */
export async function ensurePersonalSchema() {
  if (personalReady) return personalReady;
  await sql.begin(async (t) => {
    await t`CREATE SCHEMA IF NOT EXISTS ${sql(PERSONAL_SCHEMA)}`;
    // public MUST stay on the path: the created_at defaults call local_now(),
    // which is a function in public, and Postgres resolves a DEFAULT expression
    // when the CREATE TABLE runs. Without public here the schema fails to build.
    await t`SET LOCAL search_path TO ${sql(PERSONAL_SCHEMA)}, public`;
    for (const ddl of PERSONAL_TABLES) await t.unsafe(ddl);
    for (const table of PERSONAL_TABLES.map((d) => /create table if not exists (\w+)/.exec(d)?.[1]).filter(Boolean)) {
      await t.unsafe(`alter table "${PERSONAL_SCHEMA}"."${table}" enable row level security`);
    }
  });
  personalReady = PERSONAL_SCHEMA;
  console.log(`[db] schema ready: "${PERSONAL_SCHEMA}" (personal claims)`);
  return personalReady;
}

/** 'YYYY-MM' for a Date, in local time - the claim month a receipt belongs to. */
export function claimMonth(date = new Date()) {
  const d = date instanceof Date ? date : new Date(date);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
}

